#!/usr/bin/env bash
. "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)/lib.sh"

require_cmd git
cd "$ROOT"

lock="$VENDOR/versions.lock"
{
  printf '# path\tbranch\tcommit\turl\n'
  printf '# generated by scripts/versions-lock.sh -- do not edit\n'
  while read -r key path; do
    name="${key#submodule.}"
    name="${name%.path}"
    url="$(git config -f "$ROOT/.gitmodules" --get "submodule.$name.url")"
    branch="$(git config -f "$ROOT/.gitmodules" --get "submodule.$name.branch" || true)"
    commit="$(git -C "$ROOT/$path" rev-parse HEAD 2>/dev/null || echo MISSING)"
    printf '%s\t%s\t%s\t%s\n' "$path" "${branch:--}" "$commit" "$url"
  done < <(git config -f "$ROOT/.gitmodules" --get-regexp '^submodule\..*\.path$')
} > "$lock"

ok "wrote ${lock#"$ROOT"/}"
